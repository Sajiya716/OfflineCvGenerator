using System;
using System.IO;
using System.Linq;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using OfflineCvBioDataGenerator.Models;

namespace OfflineCvBioDataGenerator.PDF
{
    public class Template1_BioData : IDocument
    {
        private readonly ClientDetail _clientDetail;

        public Template1_BioData(ClientDetail clientDetail)
        {
            _clientDetail = clientDetail;
            QuestPDF.Settings.License = LicenseType.Community;
        }

        public DocumentMetadata GetMetadata() => DocumentMetadata.Default;
        public DocumentSettings GetSettings() => DocumentSettings.Default;

        public void Compose(IDocumentContainer container)
        {
            container.Page(page =>
            {
                page.Margin(40);
                page.Size(PageSizes.A4);
                page.DefaultTextStyle(x => x.FontSize(11));

                page.Header().Element(ComposeHeader);
                page.Content().Element(ComposeContent);
                page.Footer().AlignCenter().Text(text => text.Span("Generated by Offline CV & Bio-Data Generator"));
            });
        }

        private void ComposeHeader(IContainer container)
        {
            // A container may only receive ONE child, so the header row and the divider
            // line have to be wrapped together in a Column. Adding them both directly to
            // 'container' makes QuestPDF throw
            // "You should not assign multiple child elements to a single-child container".
            container.Column(column =>
            {
                column.Item().Row(row =>
                {
                    row.RelativeItem().Column(inner =>
                    {
                        inner.Item().Text(_clientDetail.Client.FullName).FontSize(20).Bold().FontColor(Colors.Blue.Medium);
                        inner.Item().Text("BIO-DATA").FontSize(14).Bold().AlignCenter();
                    });

                    byte[]? photoBytes = PdfHelper.LoadPhotoBytes(_clientDetail.Client.PhotoPath);
                    if (photoBytes != null)
                    {
                        row.ConstantItem(90).Height(90).Image(photoBytes);
                    }
                });

                column.Item().PaddingBottom(10).LineHorizontal(1).LineColor(Colors.Grey.Lighten2);
            });
        }

        private void ComposeContent(IContainer container)
        {
            container.Column(column =>
            {
                column.Item().Background(Colors.Grey.Lighten3).Padding(5).Text(text => text.Span("PERSONAL INFORMATION").FontSize(12).Bold());
                column.Item().PaddingVertical(3).Text($"Full Name: {_clientDetail.Client.FullName}");
                column.Item().PaddingVertical(3).Text($"Address: {_clientDetail.Client.Address}");
                column.Item().PaddingVertical(3).Text($"Phone: {_clientDetail.Client.Phone}");
                column.Item().PaddingVertical(3).Text($"Email: {_clientDetail.Client.Email}");
                if (_clientDetail.Client.DOB.HasValue)
                    column.Item().PaddingVertical(3).Text($"Date of Birth: {_clientDetail.Client.DOB.Value.ToShortDateString()}");
                column.Item().PaddingVertical(3).Text($"NIC: {_clientDetail.Client.NIC}");

                if (_clientDetail.EducationList.Any())
                {
                    column.Item().PaddingTop(15).Background(Colors.Grey.Lighten3).Padding(5).Text(text => text.Span("EDUCATIONAL QUALIFICATIONS").FontSize(12).Bold());
                    foreach (var edu in _clientDetail.EducationList)
                    {
                        column.Item().PaddingTop(5).Text($"Qualification: {edu.Qualification} | Institute: {edu.Institute} | Year: {edu.Year} | Results: {edu.Results}");
                    }
                }

                if (_clientDetail.ExperienceList.Any())
                {
                    column.Item().PaddingTop(15).Background(Colors.Grey.Lighten3).Padding(5).Text(text => text.Span("WORK EXPERIENCE").FontSize(12).Bold());
                    foreach (var exp in _clientDetail.ExperienceList)
                    {
                        column.Item().PaddingTop(5).Text($"Job Title: {exp.JobTitle} | Company: {exp.Company} | Duration: {exp.Duration}");
                    }
                }
            });
        }
    }
}

using System;
using System.Linq;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using OfflineCvBioDataGenerator.Models;
using Color = QuestPDF.Infrastructure.Color;

namespace OfflineCvBioDataGenerator.PDF
{
    /// <summary>
    /// Template 5 - Creative Colourful.
    ///
    /// Design: an amber accent strip above a deep teal banner holding the name and a
    /// large framed photo, then a two-column body. The tinted left column carries
    /// contact / personal details with coloured markers; the right column uses purple
    /// section titles with an amber rule and amber bullet points for every entry.
    /// </summary>
    public class CreativeColorfulTemplate : IDocument
    {
        private readonly ClientDetail _detail;

        private static readonly Color Primary = Color.FromHex("#00796B");   // deep teal
        private static readonly Color PrimaryDark = Color.FromHex("#00564A");
        private static readonly Color PrimaryTint = Color.FromHex("#E3F2F1");
        private static readonly Color Secondary = Color.FromHex("#5E35B1"); // purple
        private static readonly Color Accent = Color.FromHex("#FFA000");    // amber
        private static readonly Color Ink = Color.FromHex("#37474F");
        private static readonly Color Muted = Color.FromHex("#6E7B85");

        private const string HeadingFont = "Verdana";
        private const string BodyFont = "Segoe UI";

        public CreativeColorfulTemplate(ClientDetail detail)
        {
            _detail = detail ?? throw new ArgumentNullException(nameof(detail));
            QuestPDF.Settings.License = LicenseType.Community;
        }

        public DocumentMetadata GetMetadata() => DocumentMetadata.Default;
        public DocumentSettings GetSettings() => DocumentSettings.Default;

        public void Compose(IDocumentContainer container)
        {
            Client client = _detail.Client;

            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(0); // full-bleed banner
                page.DefaultTextStyle(x => x.FontFamily(BodyFont).FontSize(10).FontColor(Ink).LineHeight(1.45f));

                page.Content().Column(column =>
                {
                    // Thin amber strip that runs along the very top of the page.
                    column.Item().LineHorizontal(7).LineColor(Accent);

                    ComposeBanner(column, client);

                    column.Item().Row(row =>
                    {
                        row.RelativeItem(0.36f).ExtendVertical()
                            .Background(PrimaryTint).Padding(22).Column(ComposeSidebar);

                        row.RelativeItem(0.64f).Padding(26).Column(ComposeMain);
                    });
                });

                page.Footer().PaddingHorizontal(26).PaddingBottom(14).AlignCenter().Text(text =>
                {
                    text.Span("Generated by Offline CV & Bio-Data Generator").FontSize(8).FontColor(Muted);
                });
            });
        }

        // ------------------------------------------------------------------ banner

        private void ComposeBanner(ColumnDescriptor column, Client client)
        {
            column.Item().Background(Primary).PaddingHorizontal(26).PaddingVertical(24).Row(row =>
            {
                row.RelativeItem().Column(head =>
                {
                    head.Item().Text(client.FullName)
                        .FontFamily(HeadingFont).FontSize(21).Bold().FontColor(Colors.White);

                    head.Item().PaddingTop(3).Width(46).LineHorizontal(3).LineColor(Accent);

                    head.Item().PaddingTop(6)
                        .Text("CURRICULUM VITAE")
                        .FontFamily(HeadingFont).FontSize(8).LetterSpacing(0.3f)
                        .FontColor(Color.FromHex("#B2DFDB"));
                });

                byte[]? photo = PdfHelper.LoadPhotoBytes(client.PhotoPath);
                if (photo != null)
                {
                    row.ConstantItem(110).Height(110)
                        .Border(3, Colors.White).Padding(2)
                        .Image(photo).FitArea();
                }
            });
        }

        // ------------------------------------------------------------------ sidebar

        private void ComposeSidebar(ColumnDescriptor column)
        {
            Client client = _detail.Client;

            byte[]? photo = PdfHelper.LoadPhotoBytes(client.PhotoPath);
            if (photo != null)
            {
                column.Item().AlignCenter().Width(108).Height(108)
                    .Border(3, Colors.White).Padding(2)
                    .Image(photo).FitArea();

                column.Item().PaddingBottom(4);
            }

            if (HasContact(client))
            {
                SidebarHeading(column, "Contact", first: true);
                BulletLine(column, client.Phone);
                BulletLine(column, client.Email);
                BulletLine(column, client.Address);
            }

            if (client.DOB.HasValue || !string.IsNullOrWhiteSpace(client.NIC))
            {
                SidebarHeading(column, "Personal", first: !HasContact(client));

                if (client.DOB.HasValue)
                    BulletLine(column, $"Date of Birth: {client.DOB.Value:dd MMM yyyy}");

                if (!string.IsNullOrWhiteSpace(client.NIC))
                    BulletLine(column, $"NIC: {client.NIC}");
            }
        }

        private static bool HasContact(Client client)
            => !string.IsNullOrWhiteSpace(client.Phone)
               || !string.IsNullOrWhiteSpace(client.Email)
               || !string.IsNullOrWhiteSpace(client.Address);

        private static void SidebarHeading(ColumnDescriptor column, string title, bool first)
        {
            column.Item().PaddingTop(first ? 0 : 20).Text(title.ToUpperInvariant())
                .FontFamily(HeadingFont).FontSize(9.5f).Bold().LetterSpacing(0.14f).FontColor(Primary);

            column.Item().PaddingTop(3).Width(30).LineHorizontal(2.5f).LineColor(Accent);
            column.Item().PaddingTop(6);
        }

        private static void BulletLine(ColumnDescriptor column, string value)
        {
            if (string.IsNullOrWhiteSpace(value)) return;

            column.Item().PaddingTop(3).Row(row =>
            {
                row.ConstantItem(13).Text("\u2022").FontSize(11).FontColor(Accent);
                row.RelativeItem().Text(value).FontSize(9.5f).FontColor(Ink).BreakAnywhere();
            });
        }

        // ------------------------------------------------------------------ main

        private void ComposeMain(ColumnDescriptor column)
        {
            if (_detail.EducationList.Any())
            {
                SectionHeading(column, "Education", first: true);

                foreach (Education edu in _detail.EducationList)
                {
                    column.Item().PaddingTop(9).Row(row =>
                    {
                        row.ConstantItem(14).Text("\u2022").FontSize(12).FontColor(Accent);

                        row.RelativeItem().Column(entry =>
                        {
                            entry.Item().Text(edu.Qualification).FontSize(10.5f).SemiBold().FontColor(Ink);

                            string meta = JoinParts(edu.Institute, edu.Year);
                            if (meta.Length > 0)
                                entry.Item().Text(meta).FontSize(9).FontColor(Muted);

                            if (!string.IsNullOrWhiteSpace(edu.Results))
                                entry.Item().PaddingTop(1).Text(edu.Results).FontSize(9).Italic().FontColor(Secondary);
                        });
                    });
                }
            }

            if (_detail.ExperienceList.Any())
            {
                SectionHeading(column, "Work Experience", first: !_detail.EducationList.Any());

                foreach (Experience exp in _detail.ExperienceList)
                {
                    column.Item().PaddingTop(9).Row(row =>
                    {
                        row.ConstantItem(14).Text("\u2022").FontSize(12).FontColor(Accent);

                        row.RelativeItem().Column(entry =>
                        {
                            entry.Item().Text(exp.JobTitle).FontSize(10.5f).SemiBold().FontColor(Ink);

                            string meta = JoinParts(exp.Company, exp.Duration);
                            if (meta.Length > 0)
                                entry.Item().Text(meta).FontSize(9).FontColor(Muted);
                        });
                    });
                }
            }

            if (!_detail.EducationList.Any() && !_detail.ExperienceList.Any())
            {
                column.Item().PaddingTop(20).Text("No education or work experience recorded yet.")
                    .Italic().FontColor(Muted);
            }
        }

        private static void SectionHeading(ColumnDescriptor column, string title, bool first)
        {
            column.Item().PaddingTop(first ? 0 : 24).Text(title.ToUpperInvariant())
                .FontFamily(HeadingFont).FontSize(11).Bold().LetterSpacing(0.12f).FontColor(Secondary);

            column.Item().PaddingTop(4).Width(40).LineHorizontal(3).LineColor(Accent);
            column.Item().PaddingTop(6);
        }

        private static string JoinParts(params string?[] parts)
            => string.Join("  \u00B7  ", parts
                .Where(p => !string.IsNullOrWhiteSpace(p))
                .Select(p => p!.Trim()));
    }
}

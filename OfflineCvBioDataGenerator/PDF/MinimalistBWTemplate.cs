using System;
using System.Linq;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using OfflineCvBioDataGenerator.Models;
using Color = QuestPDF.Infrastructure.Color;

namespace OfflineCvBioDataGenerator.PDF
{
    /// <summary>
    /// Template 3 - Minimalist black &amp; white.
    ///
    /// Design: single column, lots of white space, a serif display font for the name and
    /// section headings, hairline separators and no colour at all (so it photocopies well).
    /// The photo sits in the top-right corner in a thin black frame.
    /// </summary>
    public class MinimalistBWTemplate : IDocument
    {
        private readonly ClientDetail _detail;

        private static readonly Color Ink = Color.FromHex("#161616");
        private static readonly Color Muted = Color.FromHex("#6F6F6F");
        private static readonly Color Hairline = Color.FromHex("#CFCFCF");

        private const string DisplayFont = "Georgia";
        private const string BodyFont = "Segoe UI";

        public MinimalistBWTemplate(ClientDetail detail)
        {
            _detail = detail ?? throw new ArgumentNullException(nameof(detail));
            QuestPDF.Settings.License = LicenseType.Community;
        }

        public DocumentMetadata GetMetadata() => DocumentMetadata.Default;
        public DocumentSettings GetSettings() => DocumentSettings.Default;

        public void Compose(IDocumentContainer container)
        {
            Client client = _detail.Client;

            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(48);
                page.DefaultTextStyle(x => x.FontFamily(BodyFont).FontSize(9.5f).FontColor(Ink).LineHeight(1.45f));

                // A container may only receive ONE child, so everything lives in one Column.
                page.Content().Column(column =>
                {
                    ComposeMasthead(column, client);
                    ComposeContact(column, client);
                    ComposeEducation(column);
                    ComposeExperience(column);

                    if (!_detail.EducationList.Any() && !_detail.ExperienceList.Any())
                    {
                        column.Item().PaddingTop(28)
                            .Text("No education or work experience recorded yet.")
                            .Italic().FontColor(Muted);
                    }
                });

                page.Footer().AlignCenter().Text(text =>
                {
                    text.Span("Generated by Offline CV & Bio-Data Generator").FontSize(7.5f).FontColor(Muted);
                });
            });
        }

        // ------------------------------------------------------------------ sections

        private void ComposeMasthead(ColumnDescriptor column, Client client)
        {
            column.Item().Row(row =>
            {
                row.RelativeItem().Column(name =>
                {
                    name.Item().Text(client.FullName.ToUpperInvariant())
                        .FontFamily(DisplayFont).FontSize(25).LetterSpacing(0.04f);

                    name.Item().PaddingTop(5)
                        .Text("CURRICULUM VITAE")
                        .FontSize(7.5f).LetterSpacing(0.22f).FontColor(Muted);
                });

                byte[]? photo = PdfHelper.LoadPhotoBytes(client.PhotoPath);
                if (photo != null)
                {
                    row.ConstantItem(92).Height(92)
                        .Border(1, Ink)
                        .Padding(3)
                        .Image(photo).FitArea();
                }
            });

            column.Item().PaddingTop(12).LineHorizontal(1.4f).LineColor(Ink);
        }

        private static void ComposeContact(ColumnDescriptor column, Client client)
        {
            string line1 = JoinParts(client.Address, client.Phone);
            string line2 = JoinParts(
                client.Email,
                client.DOB.HasValue ? $"DOB: {client.DOB.Value:dd MMM yyyy}" : null,
                string.IsNullOrWhiteSpace(client.NIC) ? null : $"NIC: {client.NIC}");

            if (line1.Length > 0)
                column.Item().PaddingTop(9).Text(line1).FontSize(9).FontColor(Muted);

            if (line2.Length > 0)
                column.Item().PaddingTop(2).Text(line2).FontSize(9).FontColor(Muted);
        }

        private void ComposeEducation(ColumnDescriptor column)
        {
            if (!_detail.EducationList.Any()) return;

            AddHeading(column, "Education");

            foreach (Education edu in _detail.EducationList)
            {
                column.Item().PaddingTop(8).Row(row =>
                {
                    row.RelativeItem().Column(left =>
                    {
                        left.Item().Text(edu.Qualification).FontSize(10.5f).SemiBold();

                        if (!string.IsNullOrWhiteSpace(edu.Institute))
                            left.Item().Text(edu.Institute).FontColor(Muted);

                        if (!string.IsNullOrWhiteSpace(edu.Results))
                            left.Item().PaddingTop(1).Text(edu.Results).Italic().FontColor(Muted);
                    });

                    if (!string.IsNullOrWhiteSpace(edu.Year))
                        row.ConstantItem(72).AlignRight().Text(edu.Year).FontSize(9).FontColor(Muted);
                });
            }
        }

        private void ComposeExperience(ColumnDescriptor column)
        {
            if (!_detail.ExperienceList.Any()) return;

            AddHeading(column, "Work Experience");

            foreach (Experience exp in _detail.ExperienceList)
            {
                column.Item().PaddingTop(8).Row(row =>
                {
                    row.RelativeItem().Column(left =>
                    {
                        left.Item().Text(exp.JobTitle).FontSize(10.5f).SemiBold();

                        if (!string.IsNullOrWhiteSpace(exp.Company))
                            left.Item().Text(exp.Company).FontColor(Muted);
                    });

                    if (!string.IsNullOrWhiteSpace(exp.Duration))
                        row.ConstantItem(112).AlignRight().Text(exp.Duration).FontSize(9).FontColor(Muted);
                });
            }
        }

        private static void AddHeading(ColumnDescriptor column, string title)
        {
            column.Item().PaddingTop(26)
                .Text(title.ToUpperInvariant())
                .FontFamily(DisplayFont).FontSize(9).Medium().LetterSpacing(0.16f).FontColor(Ink);

            column.Item().PaddingTop(4).LineHorizontal(0.8f).LineColor(Hairline);
        }

        private static string JoinParts(params string?[] parts)
            => string.Join("   |   ", parts
                .Where(p => !string.IsNullOrWhiteSpace(p))
                .Select(p => p!.Trim()));
    }
}

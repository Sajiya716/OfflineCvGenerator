using System;
using System.Linq;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using OfflineCvBioDataGenerator.Models;
using Color = QuestPDF.Infrastructure.Color;

namespace OfflineCvBioDataGenerator.PDF
{
    /// <summary>
    /// Template 4 - Corporate Gray.
    ///
    /// Design: a full-width charcoal banner across the top, then a classic
    /// "CV" two-column body: a light gray sidebar (photo, contact, personal details)
    /// and a white main column where each qualification / job is laid out as a
    /// timeline entry with the year on the left. Conservative serif headings,
    /// calm gray palette, double rule under each section title.
    /// </summary>
    public class CorporateGrayTemplate : IDocument
    {
        private readonly ClientDetail _detail;

        private static readonly Color Charcoal = Color.FromHex("#37474F");
        private static readonly Color Slate = Color.FromHex("#607D8B");
        private static readonly Color Panel = Color.FromHex("#ECEFF1");
        private static readonly Color Rule = Color.FromHex("#CFD8DC");
        private static readonly Color BodyInk = Color.FromHex("#263238");

        private const string HeadingFont = "Cambria";
        private const string BodyFont = "Calibri";

        public CorporateGrayTemplate(ClientDetail detail)
        {
            _detail = detail ?? throw new ArgumentNullException(nameof(detail));
            QuestPDF.Settings.License = LicenseType.Community;
        }

        public DocumentMetadata GetMetadata() => DocumentMetadata.Default;
        public DocumentSettings GetSettings() => DocumentSettings.Default;

        public void Compose(IDocumentContainer container)
        {
            Client client = _detail.Client;

            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(0); // full-bleed banner and sidebar
                page.DefaultTextStyle(x => x.FontFamily(BodyFont).FontSize(10).FontColor(BodyInk).LineHeight(1.4f));

                page.Content().Column(column =>
                {
                    ComposeBanner(column, client);

                    // Sidebar and main column share one row; ExtendVertical makes the
                    // sidebar panel stretch to the height of the taller main column.
                    column.Item().Row(row =>
                    {
                        row.RelativeItem(0.34f).ExtendVertical()
                            .Background(Panel).Padding(24).Column(ComposeSidebar);

                        row.RelativeItem(0.66f).Padding(28).Column(ComposeMain);
                    });
                });

                page.Footer().PaddingHorizontal(28).PaddingBottom(16).AlignCenter().Text(text =>
                {
                    text.Span("Generated by Offline CV & Bio-Data Generator").FontSize(8).FontColor(Slate);
                });
            });
        }

        // ------------------------------------------------------------------ banner

        private void ComposeBanner(ColumnDescriptor column, Client client)
        {
            column.Item().Background(Charcoal).PaddingHorizontal(28).PaddingVertical(26).Row(row =>
            {
                row.RelativeItem().Column(head =>
                {
                    head.Item().Text(client.FullName)
                        .FontFamily(HeadingFont).FontSize(24).Bold().FontColor(Colors.White);

                    head.Item().PaddingTop(4)
                        .Text("CURRICULUM VITAE")
                        .FontSize(8.5f).LetterSpacing(0.24f).FontColor(Color.FromHex("#B0BEC5"));
                });

                byte[]? photo = PdfHelper.LoadPhotoBytes(client.PhotoPath);
                if (photo != null)
                {
                    row.ConstantItem(108).Height(108)
                        .Border(3, Colors.White).Padding(2)
                        .Image(photo).FitArea();
                }
            });
        }

        // ------------------------------------------------------------------ sidebar

        private void ComposeSidebar(ColumnDescriptor column)
        {
            Client client = _detail.Client;

            byte[]? photo = PdfHelper.LoadPhotoBytes(client.PhotoPath);
            if (photo != null)
            {
                column.Item().AlignCenter().Width(112).Height(112)
                    .Border(2, Colors.White).Padding(2)
                    .Image(photo).FitArea();

                column.Item().PaddingBottom(6);
            }

            column.Item().Text(client.FullName).FontFamily(HeadingFont).FontSize(14).Bold().FontColor(Charcoal);
            column.Item().PaddingTop(2).Text("Professional Profile").FontSize(9).Italic().FontColor(Slate);

            if (HasContact(client))
            {
                SidebarHeading(column, "Contact");

                if (!string.IsNullOrWhiteSpace(client.Phone))
                    column.Item().Text(client.Phone).FontColor(BodyInk);

                if (!string.IsNullOrWhiteSpace(client.Email))
                    column.Item().Text(client.Email).FontColor(BodyInk).BreakAnywhere();

                if (!string.IsNullOrWhiteSpace(client.Address))
                    column.Item().PaddingTop(2).Text(client.Address).FontColor(BodyInk).BreakAnywhere();
            }

            if (client.DOB.HasValue || !string.IsNullOrWhiteSpace(client.NIC))
            {
                SidebarHeading(column, "Personal");

                if (client.DOB.HasValue)
                    column.Item().Text($"Date of Birth: {client.DOB.Value:dd MMM yyyy}").FontColor(BodyInk);

                if (!string.IsNullOrWhiteSpace(client.NIC))
                    column.Item().PaddingTop(2).Text($"NIC: {client.NIC}").FontColor(BodyInk);
            }
        }

        private static bool HasContact(Client client)
            => !string.IsNullOrWhiteSpace(client.Phone)
               || !string.IsNullOrWhiteSpace(client.Email)
               || !string.IsNullOrWhiteSpace(client.Address);

        private static void SidebarHeading(ColumnDescriptor column, string title)
        {
            column.Item().PaddingTop(20).Text(title.ToUpperInvariant())
                .FontFamily(HeadingFont).FontSize(10).Bold().LetterSpacing(0.12f).FontColor(Charcoal);

            column.Item().PaddingTop(3).LineHorizontal(1).LineColor(Slate);
            column.Item().PaddingTop(5);
        }

        // ------------------------------------------------------------------ main

        private void ComposeMain(ColumnDescriptor column)
        {
            if (_detail.EducationList.Any())
            {
                SectionHeading(column, "Education", first: true);

                for (int i = 0; i < _detail.EducationList.Count; i++)
                {
                    Education edu = _detail.EducationList[i];
                    if (i > 0)
                        column.Item().PaddingTop(10).LineHorizontal(0.6f).LineColor(Rule);

                    column.Item().PaddingTop(i == 0 ? 12 : 10).Row(row =>
                    {
                        row.ConstantItem(78).Text(edu.Year)
                            .FontSize(9).Bold().FontColor(Slate);

                        row.RelativeItem().Column(entry =>
                        {
                            entry.Item().Text(edu.Qualification).FontSize(11).Bold().FontColor(BodyInk);

                            if (!string.IsNullOrWhiteSpace(edu.Institute))
                                entry.Item().Text(edu.Institute).FontColor(Slate);

                            if (!string.IsNullOrWhiteSpace(edu.Results))
                                entry.Item().PaddingTop(1).Text(edu.Results).Italic().FontColor(Slate);
                        });
                    });
                }
            }

            if (_detail.ExperienceList.Any())
            {
                SectionHeading(column, "Professional Experience", first: !_detail.EducationList.Any());

                for (int i = 0; i < _detail.ExperienceList.Count; i++)
                {
                    Experience exp = _detail.ExperienceList[i];
                    if (i > 0)
                        column.Item().PaddingTop(10).LineHorizontal(0.6f).LineColor(Rule);

                    column.Item().PaddingTop(i == 0 ? 12 : 10).Row(row =>
                    {
                        row.ConstantItem(78).Text(exp.Duration)
                            .FontSize(9).Bold().FontColor(Slate);

                        row.RelativeItem().Column(entry =>
                        {
                            entry.Item().Text(exp.JobTitle).FontSize(11).Bold().FontColor(BodyInk);

                            if (!string.IsNullOrWhiteSpace(exp.Company))
                                entry.Item().Text(exp.Company).FontColor(Slate);
                        });
                    });
                }
            }

            if (!_detail.EducationList.Any() && !_detail.ExperienceList.Any())
            {
                column.Item().PaddingTop(24).Text("No education or work experience recorded yet.")
                    .Italic().FontColor(Slate);
            }
        }

        private static void SectionHeading(ColumnDescriptor column, string title, bool first)
        {
            column.Item().PaddingTop(first ? 0 : 26).Text(title.ToUpperInvariant())
                .FontFamily(HeadingFont).FontSize(13).Bold().LetterSpacing(0.1f).FontColor(Charcoal);

            column.Item().PaddingTop(5).LineHorizontal(1.6f).LineColor(Slate);
            column.Item().PaddingTop(1.5f).LineHorizontal(0.6f).LineColor(Rule);
        }
    }
}
